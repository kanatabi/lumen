#!/usr/bin/env bash
# scripts/dev-plane.sh — bootstrap the DEV OpenBao into the §5.6 shape
# (mirrors what bao_integration_test.go's bootstrapPlane does, same values):
# kv-v2 mount at `kv/`, the `fzr-portal` policy scoped to kv/* ONLY, the
# `fzr-portal` AppRole, and sample secrets so the Postman §9 folder has
# something to read. Writes dev-plane.env (gitignored) with the LUMEN_BAO_*
# exports; `make dev` picks it up automatically on the next run.
#
# Dev-only: the root token is compose's throwaway placeholder. Production
# seeds come from the INFRA §5.6 procedure, never from this script.
set -euo pipefail

BAO="${LUMEN_BAO_DEV_ADDR:-http://localhost:8200}"
ROOT="${LUMEN_BAO_DEV_ROOT:-dev-root-token}"
H=(-sS -H "X-Vault-Token: $ROOT" -H 'Content-Type: application/json')
say() { printf '  %s\n' "$*"; }

alive() { curl "${H[@]}" "$BAO/v1/sys/health" >/dev/null 2>&1; }
if ! alive; then
	echo "dev-plane: no OpenBao at $BAO — run 'make up' first" >&2
	exit 1
fi

echo "bootstrapping dev plane at $BAO"

# --- kv-v2 mount at kv/ (idempotent) ---
if curl "${H[@]}" "$BAO/v1/sys/mounts/kv" | grep -q '"type"'; then
	say "kv mount: exists"
else
	curl -X POST "${H[@]}" -d '{"type":"kv","options":{"version":"2"}}' \
		"$BAO/v1/sys/mounts/kv" >/dev/null
	say 'kv mount: created (v2)'
fi

# --- the fzr-portal policy: kv/* ONLY — no sys, nothing else (§9) ---
curl -X PUT "${H[@]}" "$BAO/v1/sys/policies/acl/fzr-portal" -d '{
  "policy": "path \"kv/data/*\" { capabilities = [\"read\", \"list\", \"create\", \"update\"] }\npath \"kv/metadata/*\" { capabilities = [\"read\", \"list\"] }\n"
}' >/dev/null
say 'policy fzr-portal: applied (kv/* only)'

# --- approle (idempotent enable; role write is create-or-update) ---
curl "${H[@]}" "$BAO/v1/sys/auth/approle" 2>/dev/null | grep -q '"type"' ||
	curl -X POST "${H[@]}" -d '{"type":"approle"}' "$BAO/v1/sys/auth/approle" >/dev/null
curl -X POST "${H[@]}" "$BAO/v1/auth/approle/role/fzr-portal" -d '{
  "token_policies": "fzr-portal",
  "token_ttl": "5m",
  "secret_id_ttl": "0",
  "token_type": "service"
}' >/dev/null
say 'approle fzr-portal: role written (token_ttl 5m — the relay re-logins constantly in dev)'

# --- sample secrets so §9 reads hit content. The staging/production pair  ---
# --- ships with ALIGNED key sets so cmd/driftcheck exits 0 — drift it     ---
# --- yourself (add one key to one env) and watch it exit 1.                ---
# purge first: the §9 collection asserts read VERSION 1 == the seed content,
# and the Go battery shares this path — deterministic v1 or no promises
curl -X DELETE "${H[@]}" "$BAO/v1/kv/metadata/lumen/dev" >/dev/null 2>&1 || true
curl -X PUT "${H[@]}" -d '{"data":{"PUBLIC_API_BASE":"http://lumen.http-server:8080","SAMPLE_KEY":"sample-value","SECRET_MARKER":"s3cr3t-v4lue-MUST-NOT-BE-LOGGED"}}' \
	"$BAO/v1/kv/data/lumen/dev" >/dev/null
curl -X PUT "${H[@]}" -d '{"data":{"PUBLIC_API_BASE":"https://gofar.id","DB_URL":"postgres://lumen:lumen-dev@localhost:5433/lumen?sslmode=disable","SESSION_JWT_SECRET":"dev-plane-sample-not-a-real-secret","MEILI_KEY":"dev-meili-key"}}' \
	"$BAO/v1/kv/data/lumen/staging" >/dev/null
curl -X PUT "${H[@]}" -d '{"data":{"PUBLIC_API_BASE":"https://gofar.id","DB_URL":"postgres://lumen:lumen-dev@localhost:5433/lumen?sslmode=disable","SESSION_JWT_SECRET":"dev-plane-sample-not-a-real-secret","MEILI_KEY":"dev-meili-key"}}' \
	"$BAO/v1/kv/data/lumen/production" >/dev/null
say 'samples: kv/lumen/{dev,staging,production} seeded (aligned key sets)'

# --- mint the relay identity, write the env file ---
ROLE=$(curl "${H[@]}" "$BAO/v1/auth/approle/role/fzr-portal/role-id" |
	sed -E 's/.*"role_id":"([^"]+)".*/\1/')
SID=$(curl -X POST "${H[@]}" "$BAO/v1/auth/approle/role/fzr-portal/secret-id" |
	sed -E 's/.*"secret_id":"([^"]+)".*/\1/')
cat >dev-plane.env <<EOF
# generated by scripts/dev-plane.sh — dev placeholders, gitignored, regen anytime
LUMEN_BAO_ADDR=$BAO
LUMEN_BAO_ROLE_ID=$ROLE
LUMEN_BAO_SECRET_ID=$SID
EOF
say 'wrote dev-plane.env — next `make dev` serves /admin/bao (restart the server to pick it up)'
